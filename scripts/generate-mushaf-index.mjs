// Generates src/data/mushafIndex.js from the `quran-meta` package (Hafs, Madinah mushaf, 604 pages).
// Run once:  npm i -D quran-meta && node scripts/generate-mushaf-index.mjs
// The output holds the global ayah number (1..6236) at which every rub' and every page starts.
// juz and hizb are derived from the rub': hizb = ceil(rub/4), juz = ceil(hizb/2).
import { writeFileSync } from 'node:fs';
import { HizbQuarterList, PageList, meta } from 'quran-meta/hafs';

if (meta.numAyahs !== 6236) throw new Error('unexpected ayah count');

// Both lists are [0, start1, start2, ..., sentinel(6237)]
const rubStarts = HizbQuarterList.slice(1, 241);
const pageStarts = PageList.slice(1, 605);
if (rubStarts.length !== 240 || pageStarts.length !== 604) throw new Error('unexpected list sizes');

const fmt = (arr) => {
  const rows = [];
  for (let i = 0; i < arr.length; i += 20) rows.push('  ' + arr.slice(i, i + 20).join(', ') + ',');
  return rows.join('\n');
};

const out = `// AUTO-GENERATED by scripts/generate-mushaf-index.mjs — do not edit by hand.
// Source: quran-meta (Hafs / Madinah mushaf). Values are GLOBAL ayah numbers (1..6236,
// counted from 1:1 in mushaf order) at which each rub' al-hizb / each page begins.

// RUB_STARTS[n - 1] = first ayah of rub' n (n = 1..240). Hizb = 4 rubs, Juz = 2 hizbs.
export const RUB_STARTS = [
${fmt(rubStarts)}
];

// PAGE_STARTS[n - 1] = first ayah of page n (n = 1..604), Madinah mushaf.
export const PAGE_STARTS = [
${fmt(pageStarts)}
];
`;
writeFileSync(new URL('../src/data/mushafIndex.js', import.meta.url), out);
console.log('written', rubStarts.length, pageStarts.length);
